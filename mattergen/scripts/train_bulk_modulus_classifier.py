"""
Train a diffusion-time bulk modulus predictor using cached MatterGen datasets and optional
synthetic structures generated by the diffusion model (labeled with an oracle).

The model takes a noisy diffusion state (x_t, t) and predicts the bulk modulus
of the clean structure x_0. It shares the GemNet backbone and timestep encoding with the
denoiser so it can be dropped into sampling-time guidance.
"""

from __future__ import annotations

import argparse
import itertools
import tempfile
import zipfile
from dataclasses import asdict
from pathlib import Path
import os

import torch
import torch.nn.functional as F
from torch_geometric.loader import DataLoader as GeoDataLoader
from torch.utils.data import random_split
from tqdm import tqdm

from mattergen.common.data.chemgraph import ChemGraph
from mattergen.common.data.dataset import CrystalDataset
from mattergen.common.data.transform import symmetrize_lattice
from mattergen.common.diffusion.corruption import (
    LatticeVPSDE,
    NumAtomsVarianceAdjustedWrappedVESDE,
)
from mattergen.common.utils.data_classes import MatterGenCheckpointInfo
from mattergen.diffusion.corruption.d3pm_corruption import D3PMCorruption
from mattergen.diffusion.corruption.multi_corruption import MultiCorruption
from mattergen.diffusion.d3pm.d3pm import MaskDiffusion, create_discrete_diffusion_schedule
from mattergen.diffusion.timestep_samplers import UniformTimestepSampler
from mattergen.generator import CrystalGenerator
from mattergen.property_predictors import BulkModulusTimeClassifier
from mattergen.guidance.calc_bulk_modulus import run_bulk_modulus_oracle


def bulk_modulus_oracle(structure) -> float:
    """
    Wrapper around the QHA-based oracle. Uses a temporary directory to avoid
    clobbering outputs when called repeatedly.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        return run_bulk_modulus_oracle(structure, outdir=tmpdir)


def structure_to_chemgraph(struct) -> ChemGraph:
    frac_coords = torch.tensor(struct.frac_coords, dtype=torch.float32) % 1.0
    cell = torch.tensor(struct.lattice.matrix, dtype=torch.float32).unsqueeze(0)
    atomic_numbers = torch.tensor(struct.atomic_numbers, dtype=torch.long)
    num_atoms = torch.tensor(len(struct), dtype=torch.long)
    material_id = getattr(getattr(struct, "properties", None), "get", lambda _k, _d=None: None)(
        "material_id", None
    )
    return ChemGraph(
        pos=frac_coords,
        cell=cell,
        atomic_numbers=atomic_numbers,
        num_atoms=num_atoms,
        num_nodes=num_atoms,
        structure_id=material_id,
    )


def build_default_corruption() -> MultiCorruption:
    pos_sde = NumAtomsVarianceAdjustedWrappedVESDE(
        wrapping_boundary=1.0, sigma_min=0.01, sigma_max=5.0, limit_info_key="num_atoms"
    )
    cell_sde = LatticeVPSDE(
        beta_min=0.1,
        beta_max=20,
        limit_density=0.05,
        limit_var_scaling_constant=0.25,
    )
    atom_corruption = D3PMCorruption(
        offset=1,
        d3pm=MaskDiffusion(
            dim=101,
            schedule=create_discrete_diffusion_schedule(kind="standard", num_steps=1000),
        ),
    )
    return MultiCorruption(
        sdes={"pos": pos_sde, "cell": cell_sde},
        discrete_corruptions={"atomic_numbers": atom_corruption},
    )


def gaussian_nll(mu: torch.Tensor, logvar: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    inv_var = torch.exp(-logvar)
    return 0.5 * ((mu - target) ** 2 * inv_var + logvar)


def run_epoch(
    *,
    model: BulkModulusTimeClassifier,
    loader: GeoDataLoader,
    corruption: MultiCorruption,
    timestep_sampler: UniformTimestepSampler,
    optimizer: torch.optim.Optimizer | None,
    device: torch.device,
    use_mse: bool,
    property_name: str,
    synthetic_loader: GeoDataLoader | None = None,
) -> float:
    is_train = optimizer is not None
    model.train(is_train)
    total_loss = 0.0
    n_batches = 0
    iter_loaders = itertools.chain(loader, synthetic_loader) if synthetic_loader is not None else loader
    for batch in tqdm(iter_loaders, desc="train" if is_train else "val"):
        batch = batch.to(device)
        if is_train:
            optimizer.zero_grad(set_to_none=True)

        targets = batch[property_name].detach().view(-1)
        t = timestep_sampler(batch_size=batch.get_batch_size(), device=device)
        noisy_batch = corruption.sample_marginal(batch, t)
        mu, logvar = model(noisy_batch, t)
        loss = F.mse_loss(mu, targets) if use_mse else gaussian_nll(mu, logvar, targets).mean()

        if is_train:
            loss.backward()
            optimizer.step()

        total_loss += loss.detach().item()
        n_batches += 1
    return total_loss / max(n_batches, 1)


def save_checkpoint(
    out_dir: Path,
    name: str,
    model: BulkModulusTimeClassifier,
    optimizer: torch.optim.Optimizer,
    epoch: int,
    cfg: dict,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    torch.save(
        {
            "epoch": epoch,
            "model_state_dict": model.state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
            "config": cfg,
        },
        out_dir / f"{name}.pt",
    )


