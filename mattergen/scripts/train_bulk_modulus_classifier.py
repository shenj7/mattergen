def main() -> None:
    args = parse_args()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    transforms = [symmetrize_lattice]
    train_dataset, val_dataset, _tmp = load_datasets(args=args, transforms=transforms)

    train_loader = GeoDataLoader(
        train_dataset, batch_size=args.batch_size, shuffle=True, num_workers=args.num_workers
    )
    val_loader = GeoDataLoader(
        val_dataset, batch_size=args.batch_size, shuffle=False, num_workers=args.num_workers
    )

    corruption = build_default_corruption()
    timestep_sampler = UniformTimestepSampler(min_t=1e-5, max_t=corruption.T)

    model = BulkModulusTimeClassifier(
        hidden_dim=args.hidden_dim,
        mlp_hidden_dim=args.mlp_hidden_dim,
        logvar_bounds=(args.logvar_min, args.logvar_max),
    ).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=args.learning_rate, weight_decay=args.weight_decay
    )

    best_val = float("inf")
    cfg = {
        "model_kwargs": asdict(model.init_config),
        "args": vars(args),
    }
    synthetic_info: MatterGenCheckpointInfo | None = None
    if args.synthetic_model_path or args.synthetic_pretrained_name:
        synthetic_info = (
            MatterGenCheckpointInfo.from_hf_hub(args.synthetic_pretrained_name)
            if args.synthetic_pretrained_name
            else MatterGenCheckpointInfo(
                model_path=Path(args.synthetic_model_path).resolve(),
                load_epoch="last",
                config_overrides=[],
            )
        )

    for epoch in range(1, args.epochs + 1):
        synthetic_loader = None
        if synthetic_info is not None and args.synthetic_num_batches > 0:
            synthetic_loader = build_synthetic_loader(
                info=synthetic_info,
                num_batches=args.synthetic_num_batches,
                batch_size=args.synthetic_batch_size,
                property_name=args.property_name,
                transforms=transforms,
                sampling_config_name=args.synthetic_sampling_config_name,
                diffusion_guidance_factor=args.synthetic_guidance_factor,
            )
        train_loss = run_epoch(
            model=model,
            loader=train_loader,
            corruption=corruption,
            timestep_sampler=timestep_sampler,
            optimizer=optimizer,
            device=device,
            use_mse=args.use_mse,
            property_name=args.property_name,
            synthetic_loader=synthetic_loader,
        )
        val_loss = run_epoch(
            model=model,
            loader=val_loader,
            corruption=corruption,
            timestep_sampler=timestep_sampler,
            optimizer=None,
            device=device,
            use_mse=args.use_mse,
            property_name=args.property_name,
        )
        print(f"epoch {epoch}: train_loss={train_loss:.4f} val_loss={val_loss:.4f}")

        save_checkpoint(
            Path(args.out_dir),
            name="last",
            model=model,
            optimizer=optimizer,
            epoch=epoch,
            cfg=cfg,
        )
        if val_loss < best_val:
            best_val = val_loss
            save_checkpoint(
                Path(args.out_dir),
                name="best",
                model=model,
                optimizer=optimizer,
                epoch=epoch,
                cfg=cfg,
            )


def build_synthetic_loader(
    *,
    info: MatterGenCheckpointInfo,
    num_batches: int,
    batch_size: int,
    property_name: str,
    transforms: list,
    sampling_config_name: str,
    diffusion_guidance_factor: float,
) -> GeoDataLoader:
    """
    Generate synthetic structures with a diffusion model, label via oracle, and wrap
    them into a GeoDataLoader for augmentation.
    """
    device = torch.get_device()
    with tempfile.TemporaryDirectory() as tmpdir:
        generator = CrystalGenerator(
            checkpoint_info=info,
            batch_size=batch_size,
            num_batches=num_batches,
            sampling_config_name=sampling_config_name,
            sampling_config_overrides=[],
            record_trajectories=False,
            diffusion_guidance_factor=diffusion_guidance_factor,
        )
        structures = generator.generate(output_dir=tmpdir)

    chemgraphs: list[ChemGraph] = []
    for struct in structures:
        cg = structure_to_chemgraph(struct)
        for t in transforms:
            cg = t(cg)
        label = torch.tensor(bulk_modulus_oracle(struct), dtype=torch.float32).view(1)
        cg = cg.replace(**{property_name: label})
        chemgraphs.append(cg)

    return GeoDataLoader(
        chemgraphs,
        batch_size=batch_size,
        shuffle=True,
        num_workers=0,
    )


def _maybe_extract_dataset(path: Path) -> tuple[Path, tempfile.TemporaryDirectory | None]:
    """
    If path is a zip archive (including git-lfs pointer once downloaded), extract to temp dir.
    Returns (cache_path, tmpdir_or_None).
    """
    if path.is_dir():
        return path, None
    if not path.exists():
        raise FileNotFoundError(f"Dataset path not found: {path}")
    if zipfile.is_zipfile(path):
        tmpdir = tempfile.TemporaryDirectory()
        with zipfile.ZipFile(path, "r") as zf:
            zf.extractall(tmpdir.name)
        return Path(tmpdir.name), tmpdir
    raise ValueError(f"Unsupported dataset path: {path}")


def _has_cache_files(folder: Path) -> bool:
    return (folder / "pos.npy").exists() and (folder / "cell.npy").exists()


def load_datasets(args, transforms):
    """
    Load train/val datasets. If explicit train/val cache dirs exist, use them.
    Otherwise, if train/val CSVs are provided, cache them and load.
    Otherwise, load a single dataset archive/folder and split into train/val,
    or use provided train/val subfolders if they exist in the archive.
    Returns (train_dataset, val_dataset, tmpdir_or_None) so caller can keep tmp alive.
    """
    props = [args.property_name]
    train_dir = Path(args.train_cache_dir)
    val_dir = Path(args.val_cache_dir)
    if _has_cache_files(train_dir) and _has_cache_files(val_dir):
        return (
            CrystalDataset.from_cache_path(cache_path=train_dir, properties=props, transforms=transforms),
            CrystalDataset.from_cache_path(cache_path=val_dir, properties=props, transforms=transforms),
            None,
        )

    # If CSVs are provided, cache them and use that.
    if args.train_csv and args.val_csv:
        csv_cache_root = Path(args.csv_cache_root)
        train_cache = csv_cache_root / "train"
        val_cache = csv_cache_root / "val"
        train_cache.mkdir(parents=True, exist_ok=True)
        val_cache.mkdir(parents=True, exist_ok=True)
        train_dataset = CrystalDataset.from_csv(
            csv_path=args.train_csv,
            cache_path=str(train_cache),
            transforms=transforms,
        )
        val_dataset = CrystalDataset.from_csv(
            csv_path=args.val_csv,
            cache_path=str(val_cache),
            transforms=transforms,
        )
        return train_dataset, val_dataset, None

    cache_root, tmpdir = _maybe_extract_dataset(Path(args.dataset_path))
    # If archive already contains train/val subfolders, use them.
    if (cache_root / "train").exists() and (cache_root / "val").exists():
        return (
            CrystalDataset.from_cache_path(cache_path=cache_root / "train", properties=props, transforms=transforms),
            CrystalDataset.from_cache_path(cache_path=cache_root / "val", properties=props, transforms=transforms),
            tmpdir,
        )

    if not _has_cache_files(cache_root):
        raise FileNotFoundError(
            f"No cache files found in {cache_root}. Expected pos.npy/cell.npy/etc. "
            "Download or unpack the cached dataset first."
        )

    full = CrystalDataset.from_cache_path(cache_path=cache_root, properties=props, transforms=transforms)
    val_size = max(1, int(len(full) * args.val_fraction))
    train_size = len(full) - val_size
    generator = torch.Generator().manual_seed(args.seed)
    train_dataset, val_dataset = random_split(full, [train_size, val_size], generator=generator)
    return train_dataset, val_dataset, tmpdir


if __name__ == "__main__":
    main()
