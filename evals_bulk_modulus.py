#!/usr/bin/env python3
"""
Compute bulk modulus for all structures generated by run_base_eval.sh.

Loads relaxed_structures.extxyz from each results/base_eval_2/ml_bulk_{gpa}_batch_{batch}/
directory, runs the E(V) curve-fitting bulk modulus estimator on every structure,
and writes a CSV + per-GPa summary.

Usage:
    python analyze_base_eval_bulk_modulus.py \
        --results-dir results/base_eval_2 \
        --output bulk_modulus_base_eval.csv \
        --n-points 5 --strain 0.03 --device cuda
"""

from __future__ import annotations

import argparse
import csv
import sys
import traceback
from pathlib import Path

import ase.io
from mattersim.forcefield import MatterSimCalculator

sys.path.insert(0, str(Path(__file__).parent))
from calc_bulk_modulus_single import calc_bulk_modulus_value

def parse_args():
    parser = argparse.ArgumentParser(description="Batch bulk modulus analysis for base_eval_2.")
    parser.add_argument(
        "--results-dir", type=Path, default=Path("results/base_eval_2"),
        help="Root results directory containing subdirectories with relaxed_structures.extxyz.",
    )
    parser.add_argument(
        "--output", type=Path, default=Path("bulk_modulus_base_eval.csv"),
        help="Output CSV path (default: bulk_modulus_base_eval.csv).",
    )
    parser.add_argument("--n-points", type=int, default=5)
    parser.add_argument("--strain",   type=float, default=0.03)
    parser.add_argument("--device",   type=str,   default=None)
    return parser.parse_args()


def find_structures(run_dir: Path):
    """Return the relaxed extxyz if it exists, else fall back to unrelaxed."""
    relaxed = run_dir / "relaxed_structures.extxyz"
    if relaxed.exists():
        return relaxed, True
    unrelaxed = run_dir / "generated_crystals.extxyz"
    if unrelaxed.exists():
        return unrelaxed, False
    return None, False


def main():
    args = parse_args()

    results_dir = args.results_dir.resolve()
    if not results_dir.is_dir():
        print(f"ERROR: {results_dir} does not exist.", file=sys.stderr)
        sys.exit(1)

    # Discover all subdirectories that have a structures file
    run_dirs = sorted([d for d in results_dir.iterdir() if d.is_dir()])
    if not run_dirs:
        print(f"ERROR: No subdirectories found in {results_dir}.", file=sys.stderr)
        sys.exit(1)
    print(f"Found {len(run_dirs)} subdirectories in {results_dir}.\n")

    # Load calculator once
    calc_kwargs = {"device": args.device} if args.device else {}
    print("Loading MatterSim calculator...")
    calc = MatterSimCalculator(**calc_kwargs)
    print("Calculator ready.\n")

    fieldnames = ["run_dir", "structure_idx", "bulk_modulus_gpa", "relaxed", "status"]

    with open(args.output, "w", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=fieldnames)
        writer.writeheader()

        total_ok = total_fail = total_missing = 0

        for run_dir in run_dirs:
            structs_path, is_relaxed = find_structures(run_dir)

            if structs_path is None:
                print(f"[{run_dir.name}] No structures file found, skipping.")
                total_missing += 1
                continue

            relax_tag = "relaxed" if is_relaxed else "UNRELAXED"
            print(f"[{run_dir.name}] Loading from {structs_path.name} ({relax_tag}) ...")

            try:
                atoms_list = ase.io.read(str(structs_path), ":")
            except Exception as e:
                print(f"  Failed to load: {e}")
                writer.writerow({
                    "run_dir": run_dir.name, "structure_idx": -1,
                    "bulk_modulus_gpa": float("nan"), "relaxed": is_relaxed,
                    "status": f"load_error: {e}",
                })
                total_fail += 1
                continue

            dir_vals = []
            for idx, atoms in enumerate(atoms_list):
                try:
                    atoms.calc = calc
                    bm = calc_bulk_modulus_value(
                        atoms, n_points=args.n_points, strain=args.strain
                    )
                    print(f"  [{idx+1}/{len(atoms_list)}] {bm:.2f} GPa")
                    writer.writerow({
                        "run_dir": run_dir.name, "structure_idx": idx,
                        "bulk_modulus_gpa": bm, "relaxed": is_relaxed, "status": "ok",
                    })
                    dir_vals.append(bm)
                    total_ok += 1
                except Exception as e:
                    print(f"  [{idx+1}/{len(atoms_list)}] FAILED: {e}")
                    writer.writerow({
                        "run_dir": run_dir.name, "structure_idx": idx,
                        "bulk_modulus_gpa": float("nan"), "relaxed": is_relaxed,
                        "status": f"error: {e}",
                    })
                    total_fail += 1

            csv_file.flush()  # persist progress after each directory

            if dir_vals:
                print(
                    f"  => {run_dir.name}: n={len(dir_vals)} | "
                    f"mean={sum(dir_vals)/len(dir_vals):.2f} | "
                    f"min={min(dir_vals):.2f} | max={max(dir_vals):.2f}\n"
                )

    print("=" * 60)
    print(f"Done. OK: {total_ok}  Failed: {total_fail}  Missing: {total_missing}")
    print(f"Results saved to: {args.output}")


if __name__ == "__main__":
    main()

